package io.github.yashkasera.alohomora.devtools

import io.github.yashkasera.alohomora.data.model.AlohomoraConfig
import io.github.yashkasera.alohomora.data.model.GitHistoryCommit
import kotlin.test.Test
import kotlin.test.assertFalse
import kotlin.test.assertTrue

/**
 * Every row of the activation table, because each one is a setup a real consumer ships with and the
 * failure is silent — DevTools simply never starts, and nothing in the app says why.
 */
class DevToolsActivationTest {

    @Test
    fun noConfigFollowsTheHostApp() {
        // Android with no Gradle plugin: the documented zero-setup path.
        assertTrue(DevToolsActivation.isEnabled(config = null, hostDebuggable = true))
        assertFalse(DevToolsActivation.isEnabled(config = null, hostDebuggable = false))
    }

    @Test
    fun currentPluginConfigOptsInEvenWhenNotDebuggable() {
        // Plugin 1.3.0+ generates `override val devToolsEnabled = true` for every enabled variant,
        // which is how a non-debuggable beta runs the server.
        assertTrue(DevToolsActivation.isEnabled(PluginConfig(devToolsEnabled = true), hostDebuggable = false))
        assertTrue(DevToolsActivation.isEnabled(PluginConfig(devToolsEnabled = true), hostDebuggable = true))
    }

    @Test
    fun configThatPredatesThePropertyFollowsTheHostApp() {
        // Plugin 1.2.0 and earlier never override the property, so they read the interface default.
        val legacy = LegacyPluginConfig()
        assertFalse(legacy.devToolsEnabled)

        assertTrue(DevToolsActivation.isEnabled(legacy, hostDebuggable = true))
        assertFalse(DevToolsActivation.isEnabled(legacy, hostDebuggable = false))
    }

    @Test
    fun explicitDecisionBeatsTheHostApp() {
        // The iOS Info.plist key: NO keeps a development build closed, YES opens a TestFlight one.
        assertFalse(DevToolsActivation.isEnabled(DecidingConfig(false), hostDebuggable = true))
        assertTrue(DevToolsActivation.isEnabled(DecidingConfig(true), hostDebuggable = false))
    }

    @Test
    fun undecidedExplicitConfigFollowsTheHostApp() {
        // The iOS Info.plist key absent: a development-signed build gets DevTools, an App Store
        // build does not.
        assertTrue(DevToolsActivation.isEnabled(DecidingConfig(null), hostDebuggable = true))
        assertFalse(DevToolsActivation.isEnabled(DecidingConfig(null), hostDebuggable = false))
    }

    /** Shaped like a config generated by plugin 1.2.0 or earlier: no `devToolsEnabled` override. */
    private open class LegacyPluginConfig : AlohomoraConfig {
        override val packageName: String? = null
        override val versionName: String = "1.0"
        override val versionCode: Int = 1
        override val variantName: String = "debug"
        override val flavorName: String? = null
        override val buildType: String? = "debug"
        override val branch: String = "main"
        override val commitSha: String = "abc123"
        override val isDirty: Boolean = false
        override val buildTimestampUtc: Long = 0L
        override val slackWebhookUrl: String? = null
        override val commits: List<GitHistoryCommit> = emptyList()
    }

    private class PluginConfig(override val devToolsEnabled: Boolean) : LegacyPluginConfig()

    private class DecidingConfig(
        override val devToolsDecision: Boolean?,
    ) : LegacyPluginConfig(), ExplicitDevToolsDecision
}
